export type StringKey = keyof (typeof strings)['tr'];

type LanguageContextValue = {
  lang: Lang;
  setLang: (next: Lang) => void;
  /** Dilleri sırayla dolaşır (en -> tr -> de -> en). Klavye/kısayol için. */
  toggleLang: () => void;
  t: (key: StringKey) => string;
};

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  // Başlangıç değeri useState'e FONKSİYON olarak veriliyor: hem depolama
  // okuması hem Intl sorgusu her render'da değil yalnızca ilk render'da
  // çalışsın. Kaydedilmiş bir seçim varsa o kazanır, yoksa cihaz diline düşer.
  // Web'de kayıtlı dil hydration'dan SONRA okunur (sunucu HTML'i dili bilmez,
  // ilk çizim 'en' ile eşleşmeli — React #418). `chosen` kullanıcı bu oturumda
  // dil değiştirdiyse dolu; değilse kayıtlı dil, o da yoksa cihaz dili.
  const hydrated = useHydrated();
  const [chosen, setLangState] = useState<Lang | null>(null);
  const lang: Lang = !hydrated ? 'en' : (chosen ?? readStoredLang() ?? detectDeviceLang());

  // setLang/toggleLang her seçimi hemen depolar — "kapanınca unutuluyor"
  // sorununun kökü buydu, state yalnızca bellekte tutuluyordu.
  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    setDeviceItem(LANG_STORAGE_KEY, next);
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((current) => {
      const base = current ?? readStoredLang() ?? detectDeviceLang();
      const next = LANGS[(LANGS.indexOf(base) + 1) % LANGS.length];
      setDeviceItem(LANG_STORAGE_KEY, next);
      return next;
    });
  }, []);

  // Web: sayfanın dili <html lang> ile bildirilir (WCAG 3.1.1). Ekran okuyucu
  // Türkçe metni İngilizce ses kurallarıyla okumasın; tarayıcı doğru tireleme yapsın.
  useEffect(() => {
    if (process.env.EXPO_OS === 'web') document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<LanguageContextValue>(
    () => ({ lang, setLang, toggleLang, t: (key) => strings[lang][key] }),
    [lang, setLang, toggleLang]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage, LanguageProvider içinde kullanılmalı');
  }
  return context;
}
