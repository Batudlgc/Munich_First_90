/**
 * Başlangıç dili: CİHAZIN dili.
 *
 * Yeni paket kurulmadı (expo-localization dahil) — `Intl` her iki platformda
 * (Hermes ve web) da mevcut. `resolvedOptions().locale` "de-DE", "tr", "en-US"
 * gibi bir BCP-47 etiketi döner; yalnızca ilk parçaya bakıyoruz.
 *
 * Eşleme: tr* -> tr, de* -> de, DİĞER HER ŞEY -> en. Bilinmeyen bir dili
 * (ör. "fr") Türkçe'ye değil İngilizce'ye düşürmek doğru olan: uygulamanın
 * hedef kitlesi uluslararası öğrenciler ve ortak dil İngilizce.
 * Intl okunamazsa (eski runtime, kısıtlı ortam) yine 'en'.
 */
export function detectDeviceLang(): Lang {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    const base = locale.toLowerCase().split(/[-_]/)[0];
    if (base === 'tr') return 'tr';
    if (base === 'de') return 'de';
    return 'en';
  } catch {
    return 'en';
  }
}

const LANG_STORAGE_KEY = 'app_language';

/**
 * Kullanıcının elle seçtiği dil — use-completed-steps.ts'in kullandığı AYNI
 * cihaz-içi depolamada (bkz. device-storage.ts) tek bir anahtar. Önceden dil
 * yalnızca cihaz dilinden geliyordu ve kullanıcı elle değiştirince uygulama
 * kapanınca unutuluyordu. Geçersiz/bozuk bir değer varsa (üç dilden biri
 * değilse) null döner, başlangıç değeri cihaz diline düşer.
 */
function readStoredLang(): Lang | null {
  const raw = getDeviceItem(LANG_STORAGE_KEY);
  return raw === 'tr' || raw === 'en' || raw === 'de' ? raw : null;
}

